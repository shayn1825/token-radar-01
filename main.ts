// token-radar-01 — the entrypoint.
//
// Reads the sealed DefiLlama snapshot, ranks every pre-token protocol
// in it by an implied launch value (see lib/model.ts), and writes the
// entry's outputs:
//
//   /output/board.json       the ranked board, one row per protocol
//   /output/dashboard/      the static page (index.html, app.css,
//                            app.js) plus z-data.js, the board data
//   /output/screenshots/    the three screenshots of the page
//   /output/dossier.json    the dossier buildDossier writes
//
// It runs twice at grade time and both runs must write the same bytes:
// everything here is a pure function of the snapshot's bytes. No
// network, no clock, no randomness, standard library only.
//
// Usage (local):  MAKEFUN_OUTPUT_DIR=out node main.ts --input <snapshot.json>
// At grade time the snapshot is /input/snapshot.json and the output
// directory is /output (or $MAKEFUN_OUTPUT_DIR when set).

import { cpSync, existsSync, mkdirSync, readFileSync, readdirSync, writeFileSync } from 'node:fs';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';
import { buildDossier } from './vendor/makefun-board.ts';
import { rankBoard } from './lib/model.ts';
import type { Snapshot } from './lib/model.ts';

const REPO_ROOT = dirname(fileURLToPath(import.meta.url));

/** The value of a `--flag value` argument, or null when absent. */
function flagValue(argv: string[], flag: string): string | null {
  const at = argv.indexOf(flag);
  return at >= 0 && at + 1 < argv.length ? argv[at + 1]! : null;
}

/** Copy a directory's regular files (one level, no recursion needed here). */
function copyFlat(fromDir: string, toDir: string): string[] {
  mkdirSync(toDir, { recursive: true });
  const names = readdirSync(fromDir, { withFileTypes: true })
    .filter((entry) => entry.isFile())
    .map((entry) => entry.name)
    .sort();
  for (const name of names) cpSync(join(fromDir, name), join(toDir, name));
  return names;
}

/**
 * The dashboard's data file: one compact array per board row, in rank
 * order, assigned to window.TOKEN_RADAR_DATA. A row is
 * [rank, slug, name, category, chains, tvl, change7d, ageDays,
 *  implied, difficulty, watchlist, farmSteps]. Numbers stay numbers
 * and nulls stay null, so the page can sort and filter on them
 * without parsing. The meta block names the snapshot, the comp table
 * and the formula, so the page can show how every value was made.
 */
function dataFileText(
  rows: ReturnType<typeof rankBoard>['rows'],
  comps: ReturnType<typeof rankBoard>['comps'],
  snapshot: Snapshot,
): string {
  const compact = rows.map((r) => [
    r.rank,
    r.slug,
    r.name,
    r.category,
    r.chains,
    r.tvl_usd,
    r.change_7d,
    r.age_days,
    r.implied_value_usd,
    r.farm_difficulty,
    r.watchlist ? 1 : 0,
    r.farm_steps,
    Math.round(r.comp_multiple * 1000) / 1000,
    Math.round(r.growth_factor * 1000) / 1000,
    Math.round(r.age_factor * 1000) / 1000,
    Math.round(r.breadth_factor * 1000) / 1000,
  ]);
  const meta = {
    asOf: snapshot.as_of,
    source: snapshot.source,
    floorUsd: snapshot.floor_usd,
    rows: rows.length,
    watchlistRows: rows.filter((r) => r.watchlist).length,
    totalImpliedUsd: rows.reduce((sum, r) => sum + r.implied_value_usd, 0),
    globalComp: Math.round(comps.global * 10000) / 10000,
    compByCategory: comps.byCategory,
    compsPerCategory: comps.compsPerCategory,
    formula: 'implied = TVL x comp x growth x age x breadth',
  };
  // One row per line, so a reader of the dossier (whose text is capped
  // at 65,536 bytes) still sees the first hundred rows whole instead
  // of losing the whole file to one over-long line.
  const lines = compact.map((row) => `  ${JSON.stringify(row)}`);
  return `// Token Radar data — generated by main.ts from the sealed snapshot.\n// One row per protocol, in rank order. See the methodology note on the page.\nwindow.TOKEN_RADAR_DATA = {\n  meta: ${JSON.stringify(meta)},\n  rows: [\n${lines.join(',\n')}\n  ]\n};\n`;
}

function main(): void {
  const argv = process.argv.slice(2);
  const inputPath = flagValue(argv, '--input') ?? '/input/snapshot.json';
  const outDir = flagValue(argv, '--out') ?? process.env.MAKEFUN_OUTPUT_DIR ?? '/output';

  const snapshot = JSON.parse(readFileSync(inputPath, 'utf8')) as Snapshot;
  const { rows, comps } = rankBoard(snapshot);

  const board = {
    as_of: snapshot.as_of,
    source: snapshot.source,
    floor_usd: snapshot.floor_usd,
    methodology:
      'implied_value_usd = tvl_usd x comp_multiple x growth_factor x age_factor x breadth_factor. ' +
      'comp_multiple is the median market-cap-to-TVL ratio of token-bearing protocols in the same category ' +
      '(at least four comparables, shrunk toward the global median; the global median otherwise). ' +
      'growth_factor is 1 plus the seven-day TVL change, clamped to [-30%, +30%]. ' +
      'age_factor rises from 0.85 to 1.15 over a protocol\'s first three years with no token recorded. ' +
      'breadth_factor adds 0.03 per chain after the first, up to five. ' +
      'A protocol "records no token" when DefiLlama records none for it; that is the snapshot\'s record, not proof it has none. ' +
      'Implied values are this entry\'s own claim, never a prediction that a token will launch.',
    rows,
  };

  mkdirSync(outDir, { recursive: true });
  mkdirSync(join(outDir, 'dashboard'), { recursive: true });
  mkdirSync(join(outDir, 'screenshots'), { recursive: true });

  writeFileSync(join(outDir, 'board.json'), `${JSON.stringify(board, null, 2)}\n`, 'utf8');

  const dashFiles = copyFlat(join(REPO_ROOT, 'dashboard'), join(outDir, 'dashboard'));
  writeFileSync(join(outDir, 'dashboard', 'z-data.js'), dataFileText(rows, comps, snapshot), 'utf8');

  const shotFiles = copyFlat(join(REPO_ROOT, 'screenshots'), join(outDir, 'screenshots'));

  writeFileSync(join(outDir, 'dossier.json'), buildDossier(outDir, { text_max_bytes: 65536 }));

  const top = rows[0]!;
  console.log(`token-radar-01: ${rows.length} rows (${rows.filter((r) => r.watchlist).length} watchlist), ` +
    `top #1 ${top.slug} $${top.implied_value_usd.toLocaleString('en-US')}, ` +
    `total implied $${rows.reduce((s, r) => s + r.implied_value_usd, 0).toLocaleString('en-US')}`);
  console.log(`dashboard files copied: ${dashFiles.join(', ')}; screenshots copied: ${shotFiles.join(', ')}`);
  console.log(`wrote ${outDir}/board.json, ${outDir}/dashboard/z-data.js, ${outDir}/dossier.json`);
}

main();
